// proxyEnv builds the Bash-subprocess env that routes child-command HTTP through
// the egress proxy (the recording MITM when capture is on, or the global proxy
// directly when it is off) and, only when a MITM CA is present, makes the common
// toolchain trust it — so tools need no manual -x/--proxy/-k. Each ecosystem reads
// a different CA var (verified empirically): SSL_CERT_FILE→curl/urllib/Go/openssl,
// REQUESTS_CA_BUNDLE→python requests (it ignores SSL_CERT_FILE), CURL_CA_BUNDLE→curl,
// GIT_SSL_CAINFO→git, NODE_EXTRA_CA_CERTS→node; NODE_USE_ENV_PROXY makes Node 24+
// honor the proxy vars. ALL_PROXY is set too so a socks5 egress proxy (which curl
// only reads from ALL_PROXY, not HTTP(S)_PROXY) works in the capture-off path.
// Empty proxyAddr → nil (direct, unchanged env).
func proxyEnv(proxyAddr, caCert string) []string {
	if proxyAddr == "" {
		return nil
	}
	env := []string{
		"HTTP_PROXY=" + proxyAddr, "HTTPS_PROXY=" + proxyAddr,
		"http_proxy=" + proxyAddr, "https_proxy=" + proxyAddr,
		"ALL_PROXY=" + proxyAddr, "all_proxy=" + proxyAddr, // socks5 egress: curl reads only this
		"NODE_USE_ENV_PROXY=1", // Node 24+: honor HTTP(S)_PROXY in built-in fetch/http
	}
	if caCert != "" {
		env = append(env,
			"SSL_CERT_FILE="+caCert,
			"CURL_CA_BUNDLE="+caCert,
			"REQUESTS_CA_BUNDLE="+caCert,
			"GIT_SSL_CAINFO="+caCert,
			"NODE_EXTRA_CA_CERTS="+caCert,
		)
	}
	return env
}

// workerDefaultTmpl is the built-in EDITABLE body (section [A]) of the worker system
// prompt, seeded into agent_prompts. The trafficTool block and the intermediate-artifact output rules
// are NOT here — they are code-owned and appended by workerSystem after rendering
// (section [B]/[C]), so editing the DB body can never drop them.
const workerDefaultTmpl = `You are the "executor" (work agent) of a network-security platform's authorized penetration-testing system. You are handed 【one intent】 (a one-line exploration direction) with a single duty: **finish this intent, write findings back to the knowledge graph, then stop and return.**

**Boundaries (red lines)**:
1. **Work only the intent you were handed**. **If while probing it you glimpse a lead worth digging that lies outside this intent** (a path leaked by an error, a possible cross-asset linkage, a suspected entry of another exploit chain), **note it in one line in a fact's summary for the planner**.
2. First-time resistance (filtered payload / 404 / injection with no echo) doesn't mean exhausted — walk all bypasses for this intent before concluding;
3. Operate only inside the authorized scope. If the top of the system prompt carries 【operation constraints】, that's the top-priority red line: self-check before every command/probe, and skip anything violating it (even if it's inside your handed intent).

**Write back as you discover** (only what's in the graph counts; what's in your head/text doesn't; write each result immediately — don't batch until the end and lose it to step exhaustion). Three write-backs, don't mix graphs:
- **New assets/resources → insert_assets (asset graph)**: subdomains / services / endpoints / fingerprints / credentials — the assets 【themselves】. **Register only assets here; exploration conclusions/judgments go to record_fact, not here.**
- **Exploration conclusions/facts → record_fact (exploration graph, pass intent_id)**: use it for everything. **Merge multiple observations into 【one】 fact** (summary = one summarizing line + detail expanding the summary, grounded in the real execution trace) — not one record per attribute; one intent usually yields one fact. Over-splitting inflates the graph endlessly — **default to one fact; fold everything that fits into detail**; only use the facts array for genuinely 【mutually independent, unmergeable】 conclusions, a rare exception, not routine. **Write only deltas**: record only what's 【newly learned】 this time; don't rephrase existing facts (pure corroboration with nothing new needs no record). **Write only what you truly saw**: give evidence (one line: command + the one or two most proving output lines, terse, details in detail) and mark confidence (observed = directly seen / inferred = inferred from signs).
- **Confirmed finding → report_finding (exploration graph, with PoC, pass intent_id)**: **only for what you truly triggered this run with reproducible evidence (request/response or command output)**. Never treat "version/fingerprint matched a CVE", "'looks injectable' parameters", or "external vuln DB / changelog / code-diff inference" as confirmed, and never substitute CVE-DB lookups or patch-version comparison for actual triggering. Trigger failed but suspicious → record an inferred fact via record_fact (the lead + why it didn't trigger) for the planner; don't force it into a finding.

After finishing this intent, summarize in one line what you did and which facts you wrote back.`

// workerTrafficBlock is section [B]: the traffic-tool note, code-injected only when
// traffic capture (recording) is on — i.e. the traffic_* tools actually exist.
// Gated on recording, NOT on the egress proxy: a global proxy with capture off
// routes traffic but records nothing, so the tools would not be there. Not stored,
// not editable.
func workerTrafficBlock(recording bool) string {
	if !recording {
		return ""
	}
	return "\n\n**Traffic tools**:\n- traffic_search / traffic_get / traffic_blob: review responses and find already-visited resources — **check traffic first, don't re-curl the same URL**. traffic_search **must specify host** and returns only 3 ultra-light index rows by default (id/method/url/status/resp_len, no body); explicitly raise limit for more; body_contains does full-text search over request/response bodies (min 3 chars, substrings and Chinese supported, e.g. passwords/keys/errors/intranet addresses); use traffic_get(id) to read one raw record, where oversized bodies show as @blob sha256:<hash> — fetch the full text in chunks with traffic_blob(hash)."
}

// artifactSpec is section [C]: the code-owned, non-editable tail appended to every
// pentest agent's prompt — intermediate artifacts must land in the shared work
// dir, never /tmp. Guaranteed present regardless of how the DB body is edited.
func artifactSpec(dir string) string {
	return "\n\n**Intermediate-artifact output rules**: scripts, payloads, captured response bodies, temp data — every intermediate artifact **goes to this task's working directory " + dir + "** (relative paths land here, and the absolute path works too) — **never /tmp, never other absolute paths**."
}

// workerArtifactSpec is the worker's section [C]: its per-intent run dir is pre-created
// by the engine (ensureRunDir), so it just writes relative paths there — no manual
// mkdir, no cross-worker name collisions.
func workerArtifactSpec(runDir string) string {
	return "\n\n**Intermediate-artifact output rules**: scripts, payloads, captured response bodies, temp data — every intermediate artifact **goes to this intent's dedicated working directory " + runDir + "** (pre-created; just write relative paths here, no need to mkdir) — **never /tmp, never other absolute paths**."
}

// ensureRunDir builds and creates an agent's working directory under base:
// <base>/tasks/<taskID> for planner/main; <base>/tasks/<taskID>/i<intentID> for a
// worker (intentID<=0 → task dir only). The "tasks/" segment groups per-task dirs
// symmetrically with the chat agent's "sessions/<sessionID>". Best-effort mkdir — on
// failure, writes fail the same way an unwritable CWD would.
func ensureRunDir(base string, taskID, intentID int64) string {
	dir := filepath.Join(base, "tasks", strconv.FormatInt(taskID, 10))
	if intentID > 0 {
		dir = filepath.Join(dir, "i"+strconv.FormatInt(intentID, 10))
	}
	_ = os.MkdirAll(dir, 0o755)
	return dir
}

// cmdOutDir is the SDK large-tool-output spill dir under an agent's run dir.
func cmdOutDir(dir string) string { return filepath.Join(dir, "cmd-output") }

func workerSystem(proxyAddr, caCert, dataDir, runDir string) string {
	body := renderSystem("worker", workerDefaultTmpl, WorkerVars{ProxyAddr: proxyAddr, DataDir: dataDir, Now: nowStr()})
	// caCert is present only when the recording MITM is on, which is exactly when
	// the traffic_* tools are registered — so it gates the traffic-tool note.
	// Optional finding guidance is added for every role after tool resolution.
	return body + workerTrafficBlock(caCert != "") + workerArtifactSpec(runDir)
}

// renderIntentTask formats the claimed intent for the worker's launch USER message:
// the intent is the worker's whole job. It used to live in the system prompt; it now
// rides in the first user turn (together with the situational overview) so the system
// prompt stays static/role-only — same move as the planner's situational block.
// intentAssetIDs pulls the intent's target asset ids out of its payload
// (planner's add_intent stores them as a numeric asset_ids array). nil on absence
// or malformed payload.
func intentAssetIDs(intent *db.Node) []int64 {
	if intent == nil {
		return nil
	}
	var p struct {
		AssetIDs []int64 `json:"asset_ids"`
	}
	if err := json.Unmarshal(intent.Payload, &p); err != nil {
		return nil
	}
	return p.AssetIDs
}

func renderIntentTask(intent *db.Node) string {
	return fmt.Sprintf("\n\n【Your assigned intent (this run's only job: do just this, produce only facts, stop when done)】：\n%s\nIntent id: %d (pass it when writing back via record_fact / report_finding)", string(intent.Payload), intent.ID)
}

// renderWorkerGraphOverview folds the global situational snapshot into the worker's
// launch USER message for AWARENESS ONLY. The framing is deliberately strong: the overview
// must NOT widen the worker's job — it still does only its assigned intent. Its sole
// purpose is letting the worker read context (existing facts/assets/hints)
// so it avoids redundant work and doesn't re-derive what others already found.
func renderWorkerGraphOverview(data map[string]any) string {
	// coverage is the planner's signal for "which classes are under-tested / whether to widen scope", and clashes with the
	// worker's mandate boundary of "do only the assigned intent, don't chase uncovered spots" → strip it from the worker
	// view. data is this worker's own fresh map; deleting keys doesn't affect the planner.
	delete(data, "coverage")
	b, err := json.Marshal(data)
	if err != nil {
		return "" // fall back silently: the worker just won't have the global context
	}
	return "\n\n【Global exploration posture (read-only, to situate your own intent in the big picture)】：\n" +
		"Below is the whole task's current exploration snapshot. Two uses: first, know what others already found so you don't repeat it; second, connect your own intent to the global picture while probing it.\n" +
		"**Divergence is good**: think deep and wide while probing this intent. The only line is — don't actually go execute other intents (that's other workers' jobs, scheduled by the planner). Whenever a valuable lead occurs to you (a cross-asset linkage, a suspected entry of another exploit chain, a globally suspicious point), **write it into a fact for the planner** — that's important output, not optional. Better to over-report one for the planner to judge than swallow it yourself.\n" +
		string(b)
}

// Execute runs one intent. hooks (the per-task Guard) gates every tool call; may
// be nil. emit, if non-nil, receives one ActivityRecord per execution step.
// notifyFinding, if non-nil, is called (intentID, summary) when this worker writes
// a finding (report_finding) so the task's planner wakes mid-flight — with context
// on which intent found what — instead of waiting for the worker to finish.
// Returns the terminal reason (so the engine can distinguish completed vs
// max_turns) and a per-kind breakdown of what was written back (so an intent that
// explored but persisted nothing isn't mistaken for done, and the engine can log
// facts/assets/findings separately instead of lumping them under "facts").
func (w *Worker) Execute(ctx context.Context, name string, taskID int64, as *db.AssetStore, ts *db.ExplorationStore, intent *db.Node, hooks harness.HookRunner, emit func(db.Activity), enr EnrichTrigger, notifyFinding func(int64, string)) (harness.TerminalReason, WriteCounts, error) {
	return w.execute(ctx, name, taskID, as, ts, intent, hooks, emit, enr, notifyFinding, "", "")
}

// ExecuteWithMessage runs the next turn in the same intent conversation with a
// human-authored message. The HTTP handler does not edit the transcript;
// agentcore records the message as a normal user turn when this Worker starts.
// This keeps Worker continuation identical to the regular agent chat flow.
func (w *Worker) ExecuteWithMessage(ctx context.Context, name string, taskID int64, as *db.AssetStore, ts *db.ExplorationStore, intent *db.Node, hooks harness.HookRunner, emit func(db.Activity), enr EnrichTrigger, notifyFinding func(int64, string), requestID, message string) (harness.TerminalReason, WriteCounts, error) {
	return w.execute(ctx, name, taskID, as, ts, intent, hooks, emit, enr, notifyFinding, strings.TrimSpace(requestID), strings.TrimSpace(message))
}

func (w *Worker) execute(ctx context.Context, name string, taskID int64, as *db.AssetStore, ts *db.ExplorationStore, intent *db.Node, hooks harness.HookRunner, emit func(db.Activity), enr EnrichTrigger, notifyFinding func(int64, string), requestID, message string) (harness.TerminalReason, WriteCounts, error) {
	tsx := NewToolSet(ts, name)
	tsx.SetFindingRecorder(w.findingRecorder)
	tsx.SetTaskID(taskID)
	coverageEnabled := as == nil || as.CoverageEnabled(taskID)
	tsx.SetCoverageEnabled(coverageEnabled)
	if as != nil {
		tsx.SetAssetStore(as, as.Companies())
	}
	tsx.SetOwnerNode(intent.ID)         // assets this worker discovers anchor to its intent → visible to the task
	tsx.SetEnrich(enr)                  // async DNS/HTTP auto-completion for assets this worker writes
	tsx.SetNotifyFinding(notifyFinding) // wake the planner on the spot when report_finding lands, carrying "which intent + finding"
	// base = built-in worker tools ∪ host tools (traffic) ∪ default tools (incl. Bash);
	// then augment with the agent's visible skills/MCP. During the SDK settlement
	// phase, Bash is hidden via Settlement.DisabledTools (no local gating needed).
	base := append(tsx.WorkerTools(), w.extraTools...)
	// worker deliberately gets no MultiEdit/Glob/Grep: precise file edits use Edit, search goes through Bash (grep/find) —
	// narrower tool surface, fewer low-value calls. The rest of the SDK default tools (Read/Write/Edit/LS/Bash/Sleep) stay.
	base = append(base, defaultToolsExcept("MultiEdit", "Glob", "Grep")...)
	ctx = WithRunInfo(ctx, RunInfo{TaskID: taskID, ExplorationID: explorationID(ts), IntentID: intent.ID})
	tools, def, cleanup := AugmentTools(ctx, "worker", base)
	defer cleanup()

	// The intent is the worker's 【sole mandate, the invariant spanning the whole run】 → it goes into the system prompt together
	// with the launch instructions and the intent-anchored target assets' raw data: system is re-assembled every run and can
	// never be compacted away, so the intent is always present even in long runs, and resumed runs don't depend on whether the
	// transcript history kept that first message. Cost: per-intent volatile data pollutes system and loses cross-intent cache
	// reuse; a deliberate tradeoff (losing the intent is far worse than saving tokens).
	// The fork from the planner's "posture block goes in the user turn" is intentional: the planner is the intent producer with
	// no single mandate; the worker has one. Only the 【global posture overview】 stays in the launch user message — it's
	// degradable, tolerates staleness, harmless if compacted.
	// This intent's dedicated working directory <workDir>/tasks/<taskID>/i<intentID>, pre-created engine-side.
	runDir := ensureRunDir(w.workDir, taskID, intent.ID)
	// The run-wide intent is not the current tool action. Do not forward it or
	// inherit a parent run's background into the action reviewer.
	ctx = intercept.WithReviewContext(ctx, runDir, intercept.ReviewBackground{})
	overview := renderWorkerGraphOverview(tsx.graphOverviewData())
	sysBody := workerSystem(w.proxyAddr, w.proxyCACert, w.workDir, runDir)
	if w.wantConstraints() {
		sysBody += constraintBlock(ts) // operation constraints (if any) injected into the system prompt; the worker obeys strictly at execution
	}
	// intent block → intent-anchored asset block → launch instructions, appended to the system tail in order (same append scheme as constraintBlock).
	sysBody += renderIntentTask(intent)
	if as != nil {
		if ids := intentAssetIDs(intent); len(ids) > 0 {
			if assets, err := as.GetByIDs(ids); err == nil && len(assets) > 0 {
				if b, err := json.Marshal(assets); err == nil {
					sysBody += "\n\nTarget assets matching this intent's asset_ids:\n" + string(b)
				}
				// Assets this intent explicitly targets → auto-include in the task test scope (same conservative
				// granularity as insertAssets). upsertTaskScope's ON CONFLICT DO NOTHING + uq_task_scope
				// unique index guarantees no duplicate adds; re-runs/retries are equally idempotent no-ops.
				// Scope stops accumulating when asset-coverage is off (the denominator).
				if coverageEnabled {
					for _, a := range assets {
						_ = as.AddAutoScope(taskID, a.Type, a.Domain, a.URL, a.IP)
					}
				}
			}
		}
	}
	sysBody += "\n\nStart executing the intent above: do just it, produce only facts, assets, findings, then stop."
	system, boundary := deferredSystem(sysBody, def)
	// Task-level deadline (injected via ctx) squeezes this run's wall-clock budget + picks settle words (see taskclock.go).
	tc := taskClockFrom(ctx)
	maxDur, clamped := clampMaxDuration(tc.DeadlineUnix, w.runTimeout)
	settle := wrapupSettlement("worker", []string{"Bash"})
	if tc.DeadlineUnix > 0 {
		settle = wrapupSettlementForTask("worker", []string{"Bash"}, clamped)
	}
	opts := agentcore.Options{
		Provider:        w.prov,
		SystemPrompt:    system,
		DynamicBoundary: boundary,
		Tools:           tools,
		DeferredTools:   def.Deferred,
		UnlockSet:       def.Unlock,
		PermissionMode:  permission.ModeBypass,
		// WebFetch goes through the recording proxy; its HTTP is traced just like curl's; loading the proxy CA lets
		// MITM re-signed HTTPS certs 【verify normally】 (instead of disabling verification). Empty proxy = direct.
		EnableWebFetch: true,
		WebFetchProxy:  w.proxyAddr,
		WebFetchCACert: w.proxyCACert,
		// Web search (optional). ddgs needs no key; brave-free needs BraveKey; tavily needs TavilyKey.
		// WebSearchProxy is a separate egress proxy (http/https/socks5), unrelated to the traffic-recording MITM proxy; empty = direct.
		EnableWebSearch:       w.webSearch.Enabled,
		WebSearchBackend:      w.webSearch.Backend,
		BraveSearchAPIKey:     w.webSearch.BraveKey,
		TavilySearchAPIKey:    w.webSearch.TavilyKey,
		DeepSeekSearchBaseURL: w.webSearch.DeepSeekBaseURL,
		DeepSeekSearchAPIKey:  w.webSearch.DeepSeekAPIKey,
		DeepSeekSearchModel:   w.webSearch.DeepSeekModel,
		WebSearchProxy:        w.webSearch.Proxy,
		// Bash child-command HTTP uses the recording proxy by default + trusts its CA (tools need no -x/-k).
		BashEnv:    proxyEnv(w.proxyAddr, w.proxyCACert),
		WorkingDir: runDir,
		MaxTurns:   w.maxTurns, // 0 = unlimited (configurable in agent management)
		// wall-clock budget, judged at turn boundaries, never interrupting mid-flight; 0 = unlimited. With a task-level deadline,
		// squeezed to min(own budget, time left to deadline) so this run settles naturally at task time (see taskclock.go).
		MaxDuration: maxDur,
		// hitting the budget (turns OR duration) → SDK runs one settle turn (Bash hidden), writing back what's identified, no dangling tail.
		// when clamped (squeezed by the task deadline), PromptByReason: timeout = task time → task-timeout words;
		// steps = steps ran out inside the squeeze window → fall back to per-run words. Unclamped stays purely per-run.
		Settlement: settle,
		// large tool output spills to cmd-output/ with a head + pointer (SDK tool.Capture);
		// full output preserved on disk. Truncation cap uses the SDK default (30000 chars).
		ToolOutputDir: cmdOutDir(runDir),
		Compaction:    compactionConfig(w.compactionWindow()), // long tool-heavy runs stay within the window
		Todos:         actool.NewTodoStore(),                  // session-scoped scratch todos (TodoWrite), planning only, dropped on exit
		NonStreaming:  w.nonStreaming(),                       // when the profile selects non-streaming, go through Provider.Complete
		MaxTokens:     w.maxTokens(),                          // 0 = send no cap, the server default decides
	}
	if hooks != nil { // typed-nil guard: only set when concrete (avoids harness panic)
		opts.Hooks = hooks
	}
	if w.tx != nil { // persist raw LLM conversation; one file per worked intent
		opts.Transcript = w.tx
		opts.SessionID = WorkerSessionID(ts.ID(), intent.ID)
	}
	intentID := intent.ID
	emitWrap := func(r db.Activity) {
		if emit != nil {
			r.NodeID, r.Worker = &intentID, name
			emit(r)
		}
	}
	// intent / launch instructions / intent-anchored assets already went down with the system prompt (see sysBody assembly above).
	// This launch user message carries only the 【global posture overview】 — degradable big-picture context, harmless if compacted.
	// On the rare marshal failure the overview is empty; fall back to one launch sentence so the first turn never has an empty user message.
	input := overview
	if strings.TrimSpace(input) == "" {
		input = "Start executing the intent from system: do just it, produce only facts, assets, findings, then stop."
	}

	// experimental: when enabled, noa takes over context compaction (archives land together under <workDir>/noa/<SessionID>, persisted).
	noaSession := WorkerSessionID(ts.ID(), intent.ID)
	enableNoa(&opts, w.noaEnabledFn, w.workDir, noaSession, noaWarn(noaSession))
	ctx = attachSideCapture(ctx, &opts)
	s := agentcore.NewSession(opts)
	defer s.Close() // release the session's background-task manager (temp dir + processes)

	// Resume prior conversation if this intent was paused/blocked/exhausted and is
	// being re-run. The transcript ID is deterministic per intent, so if a prior
	// session exists the worker continues from where it left off instead of
	// restarting from scratch.
	alreadyRecorded := false
	if w.tx != nil {
		_ = s.Resume(opts.SessionID)
		alreadyRecorded = requestID != "" && hasWorkerChatMessage(s.Messages(), requestID)
		if len(s.Messages()) > 0 && message == "" {
			seedUnlockFromHistory(s.Messages(), def.UnlockSkill)
			input = "Keep executing."
		} else if len(s.Messages()) > 0 {
			seedUnlockFromHistory(s.Messages(), def.UnlockSkill)
		}
	}
	if message != "" {
		if alreadyRecorded {
			input = "Continue executing the new intent from the latest human chat input. Don't repeat completed actions."
		} else if len(s.Messages()) > 0 {
			input = workerChatMarker(requestID) + "\n【New intent from human chat input】\n" + message +
				"\n\nExecute this human input immediately, then decide from context whether the original task needs to continue."
		} else {
			input += "\n\n" + workerChatMarker(requestID) + "\n【New intent from human chat input】\n" + message +
				"\n\nPrioritize this human input."
		}
	}

	// Budgets + settlement are owned by the SDK (MaxTurns/MaxDuration + Settlement):
	// on hit it runs a wrap-up turn and finishes with ReasonMaxTurns/ReasonTimeout.
	// MaxDuration now interrupts an in-flight tool at the wall-clock deadline and
	// enters the wrap-up phase on the live ctx, so a run whose tool overran the budget
	// still settles (no external hard-timeout backstop needed). ctx itself carries only
	// pause / planner kill / shutdown, which the engine distinguishes and re-queues/stops.
	_, reason, err := captureRunSession(ctx, s, input, emitWrap)
	return reason, tsx.Writes(), err
}
