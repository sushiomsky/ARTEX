// addOneGoal hangs one goal node (open) on the exploration graph: linked to the task root (origin fact, rel spawns).
// origin takes t.worker (default system): the goals decomposer writes "goals", the main agent at runtime writes
// "human". Waking the planner is done by setGoals once for the whole batch (see below); this only persists.
func (t *ToolSet) addOneGoal(it goalItem) (int64, error) {
	text := strings.TrimSpace(it.Text)
	if text == "" {
		return 0, fmt.Errorf("text is required")
	}
	payload := map[string]any{"text": text}
	if vc := strings.TrimSpace(it.VulnClass); vc != "" {
		payload["vulnclass"] = vc
	}
	origin := t.worker
	if origin == "" {
		origin = "system"
	}
	id, err := t.ts.AddNode(db.KindGoal, payload, 0, "open", origin, nil)
	if err != nil {
		return 0, err
	}
	if of, _ := t.ts.OriginFactID(); of > 0 && id > 0 {
		_ = t.ts.Link(of, db.RelSpawns, id) // goals descend from the task root (origin fact)
	}
	return id, nil
}

// setGoals adds exploration goals (goal nodes) to 【this task】. It's both the goals decomposer's submit tool and the main
// agent's runtime goal-adding tool — one managed tool, web-editable description/schema and per-agent binding.
func (t *ToolSet) setGoals() actool.CoreTool {
	return writeTool("set_goals",
		"Add exploration goals (goals) to 【this task】. Goal = a final deliverable/verifiable outcome — not attack steps or recon actions.\n"+
			"★Prefer batching: submit several goals at once in the goals array; returns ids matching it in length and order (failed items get id=0, see errors). For a single goal, omit goals and give top-level text directly.\n"+
			"vulnclass optional: matching vuln class (e.g. SQLi/IDOR); leave empty for business-logic goals. Whether goals are met is judged and marked met by the system; this tool only adds.",
		obj(map[string]any{
			"goals":     map[string]any{"type": "array", "description": "【Prefer this】 array of goals to add, processed in order. Each element: text (required — one standalone verifiable final goal) + vulnclass (optional). Returned ids match this array in length and order.", "items": map[string]any{"type": "object"}},
			"text":      str("[single] One standalone verifiable final goal"),
			"vulnclass": str("[single] Matching vuln class (if clear), e.g. SQLi/IDOR; business-logic goals may leave empty"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.ts == nil {
				return actool.Errorf("set_goals not enabled: ExplorationStore not initialized"), nil
			}
			var a struct {
				Goals    []goalItem `json:"goals"`
				goalItem            // single mode: top-level text/vulnclass
			}
			_ = json.Unmarshal(in, &a)
			batch := len(a.Goals) > 0
			items := a.Goals
			if !batch {
				items = []goalItem{a.goalItem}
			}

			ids := make([]int64, len(items))
			errs := map[string]string{}
			var addedTexts []string
			for i, it := range items {
				id, err := t.addOneGoal(it)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				ids[i] = id
				addedTexts = append(addedTexts, strings.TrimSpace(it.Text))
			}
			if len(addedTexts) > 0 {
				// Wake the planner (once per batch). Prefer notifyGoal: one set_goals records one "human added
				// N goals: ..." trigger instead of spamming per item; decomposer/worker have no such callback → fall back
				// to bare notify (decomposer round-0 has no notify wired either, i.e. no-op, since the planner isn't up yet).
				switch {
				case t.notifyGoal != nil:
					t.notifyGoal(addedTexts)
				case t.notify != nil:
					t.notify()
				}
				// A main-agent runtime goal addition → pull finished/paused tasks back to running to continue (the terminal gate
				// swallows plain notifies — explicit revival required). Only mainagent wires this callback; decomposer/worker get nil.
				if t.resumeTask != nil {
					t.resumeTask()
				}
			}

			if !batch { // single: keep the original return shape
				if e, bad := errs["0"]; bad {
					return actool.Errorf(e), nil
				}
				return actool.Text(fmt.Sprintf("goal added: %d", ids[0])), nil
			}
			out := map[string]any{"ids": ids}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		})
}

