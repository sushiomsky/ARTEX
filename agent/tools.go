type hintItem struct {
	Text        string            `json:"text"`
	AssetIDs    []json.RawMessage `json:"asset_ids"`
	TrafficRefs []db.TrafficRef   `json:"traffic_refs"`
}

// addOneHint hangs one hint node (active/human) on the exploration graph, anchorable to assets, returning its id.
func (t *ToolSet) addOneHint(it hintItem) (int64, error) {
	if len(it.TrafficRefs) > 0 && !findingTrafficBindingEnabled() {
		return 0, fmt.Errorf("Agent auto traffic binding is off; the hint carrying traffic_refs was not saved. Enable it in system settings, or hand off text only")
	}
	if strings.TrimSpace(it.Text) == "" {
		return 0, fmt.Errorf("text is required")
	}
	var anchors []int64
	for _, raw := range it.AssetIDs {
		if tid := pid(raw); tid > 0 {
			anchors = append(anchors, tid)
		}
	}
	refs, err := db.NormalizeTrafficRefs(it.TrafficRefs)
	if err != nil {
		return 0, err
	}
	payload := map[string]any{"text": it.Text}
	if len(refs) > 0 {
		payload["traffic_refs"] = refs
	}
	// Planner wake-ups aren't fired per item here — addHint fires once for the whole batch after writing (carrying the hint
	// text), so one add_hint with many hints doesn't spam the planner's trigger lines one per hint.
	return t.ts.AddNode(db.KindHint, payload, 0, "active", "human", anchors)
}

