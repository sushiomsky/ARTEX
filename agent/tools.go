// addOneConstraint lands one operation constraint in task_constraints. origin takes t.worker (default system):
// the decomposer writes "goals", the main agent writes "human".
func (t *ToolSet) addOneConstraint(it constraintItem) (int64, error) {
	text := strings.TrimSpace(it.Text)
	if text == "" {
		return 0, fmt.Errorf("text is required")
	}
	kind := strings.TrimSpace(strings.ToLower(it.Type))
	if kind == "" {
		kind = "deny" // default to forbid: more conservative when untyped
	}
	if kind != "allow" && kind != "deny" {
		return 0, fmt.Errorf("type must be allow or deny")
	}
	return t.ts.AddConstraint(kind, text, t.worker)
}

// setConstraints adds operation constraints (allow = what may be done / deny = what is forbidden) to 【this task】. It's both the
// decomposer round-0 constraint-extraction submit tool and the main agent's runtime constraint tool — one managed tool, web-editable
// description/schema and per-agent binding. Constraints are injected into planner/worker system prompts to bound exploration.
func (t *ToolSet) setConstraints() actool.CoreTool {
	return writeTool("set_constraints",
		"Add operation constraints to 【this task】 to bound exploration: type=allow (operations allowed) or deny (operations forbidden).\n"+
			"Constraint = a rule about 'which operations may/may not be done' (e.g. 'only test the current port, scan no others', 'no writes to the production DB', 'passive recon only') — not a goal, not attack steps.\n"+
			"★Prefer batching: submit several in the constraints array at once; returns ids matching it in length and order (failed items get id=0, see errors). For a single constraint, omit constraints and give top-level text/type directly.\n"+
			"Register only constraints 【explicitly stated】 in the task goal/description — never invent; when unsure of the type use deny (more conservative).",
		obj(map[string]any{
			"constraints": map[string]any{"type": "array", "description": "【Prefer this】 array of constraints to add, processed in order. Each element: text (required — one constraint) + type (allow|deny). Returned ids match this array in length and order.", "items": map[string]any{"type": "object"}},
			"text":        str("[single] One operation constraint's content"),
			"type":        str("[single] allow (allowed) or deny (forbidden); omitted defaults to deny"),
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			if t.ts == nil {
				return actool.Errorf("set_constraints not enabled: ExplorationStore not initialized"), nil
			}
			var a struct {
				Constraints    []constraintItem `json:"constraints"`
				constraintItem                  // single mode: top-level text/type
			}
			_ = json.Unmarshal(in, &a)
			batch := len(a.Constraints) > 0
			items := a.Constraints
			if !batch {
				items = []constraintItem{a.constraintItem}
			}
			ids := make([]int64, len(items))
			errs := map[string]string{}
			for i, it := range items {
				id, err := t.addOneConstraint(it)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				ids[i] = id
			}
			if !batch { // single: keep the simple return shape
				if e, bad := errs["0"]; bad {
					return actool.Errorf(e), nil
				}
				return actool.Text(fmt.Sprintf("constraint added: %d", ids[0])), nil
			}
			out := map[string]any{"ids": ids}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		})
}

func (t *ToolSet) addHint() actool.CoreTool {
	return t.writeExpTool("add_hint", "Hang a human/main-agent strategic hint on the exploration graph; the planner reads it next time it generates intents.\n"+
		"★Prefer batching: submit several hints at once in the hints array (fewer round-trips than one-by-one). Returns an ids array, same length and order as hints (failed items get id=0, see errors). For a single hint, omit hints and give top-level text directly.",
		obj(map[string]any{
			"hints":        map[string]any{"type": "array", "description": "【Prefer this】 array of hints to add, processed in order. Each element's fields mirror the top-level fields below (text/asset_ids/traffic_refs). Returned ids match this array in length and order.", "items": obj(map[string]any{"text": str("Hint content"), "asset_ids": map[string]any{"type": "array", "items": map[string]any{"type": "integer"}}, "traffic_refs": HintTrafficSchema()})},
			"text":         str("[single] Hint content, e.g. 'prioritize post-auth interfaces'"),
			"traffic_refs": HintTrafficSchema(),
			"asset_ids":    map[string]any{"type": "array", "items": map[string]any{"type": "integer"}, "description": "Anchored asset ids (optional, 0/1/many)"},
		}),
		func(_ context.Context, in json.RawMessage) (actool.Result, error) {
			var a struct {
				Hints    []hintItem `json:"hints"`
				hintItem            // single mode: top-level text/asset_ids
			}
			_ = json.Unmarshal(in, &a)
			batch := len(a.Hints) > 0
			items := a.Hints
			if !batch {
				items = []hintItem{a.hintItem}
			}

			ids := make([]int64, len(items))
			errs := map[string]string{}
			var addedTexts []string
			for i, it := range items {
				id, err := t.addOneHint(it)
				if err != nil {
					errs[strconv.Itoa(i)] = err.Error()
					continue
				}
				ids[i] = id
				addedTexts = append(addedTexts, strings.TrimSpace(it.Text))
			}
			if len(addedTexts) > 0 {
				// Wake the planner (once per batch). Prefer notifyHint: one add_hint records one "human added
				// N strategic hints: ..." trigger so the planner knows "this turn fired on a new hint" and sees the hint
				// content; without that callback fall back to bare notify (bare wake — the hint still folds into the graph
				// for it to read itself).
				switch {
				case t.notifyHint != nil:
					t.notifyHint(addedTexts)
				case t.notify != nil:
					t.notify()
				}
			}

			if !batch { // single: keep the original return shape
				if e, bad := errs["0"]; bad {
					return actool.Errorf(e), nil
				}
				return actool.Text(fmt.Sprintf("hint added: %d", ids[0])), nil
			}
			out := map[string]any{"ids": ids}
			if len(errs) > 0 {
				out["errors"] = errs
			}
			return jsonResult(out)
		})
}

